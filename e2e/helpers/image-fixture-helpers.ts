export type ImageKind = 'png' | 'jpg' | 'jpeg' | 'gif' | 'svg' | 'webp'

/**
 * Generate a short random-ish tab id for test isolation. Not cryptographically
 * random — just enough to avoid collisions between parallel test runs.
 */
export function makeTabId(prefix = 't'): string {
  const rand = Math.random().toString(36).slice(2, 10)
  const time = Date.now().toString(36).slice(-4)
  return `${prefix}-${rand}${time}`
}

function bytesFor(kind: ImageKind): Buffer {
  switch (kind) {
    case 'png':
      return TINY_PNG_BYTES
    case 'jpg':
    case 'jpeg':
      return TINY_JPEG_BYTES
    case 'gif':
      return TINY_GIF_BYTES
    case 'svg':
      return TINY_SVG_BYTES
    case 'webp':
      return TINY_WEBP_BYTES
  }
}

/**
 * Holds a temporary directory for test image fixtures.
 */
export class ImageFixtureDir {
  constructor(public readonly dir: string) {}

  static async create(prefix = 'wrangle-img-'): Promise<ImageFixtureDir> {
    const dir = await mkdtemp(path.join(tmpdir(), prefix))
    return new ImageFixtureDir(dir)
  }

  /**
   * Write a fixture image into the temp directory and return its absolute path.
   */
  async writeImage(filename: string, kind?: ImageKind): Promise<string> {
    const ext = (path.extname(filename).slice(1).toLowerCase() as ImageKind) || 'png'
    const effective = kind ?? (ext as ImageKind)
    const absPath = path.join(this.dir, filename)
    await mkdir(path.dirname(absPath), { recursive: true })
    await writeFile(absPath, bytesFor(effective))
    return absPath
  }

  async cleanup(): Promise<void> {
    await rm(this.dir, { recursive: true, force: true })
  }
}
